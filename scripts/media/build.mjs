// Offline generator of the exercise mannequin images (dev tool; nothing here ships to users).
//   node scripts/media/build.mjs [slug …] [--sheet]     → public/exercise-media/<male|female>/<slug>/<1..3>.webp  (+ a contact sheet in /tmp with --sheet)
import { createServer } from "node:http";
import { readFileSync, mkdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import sharp from "sharp";
import { EXERCISES } from "./poses.mjs";

const here = dirname(fileURLToPath(import.meta.url)), root = join(here, "..", "..");
const args = process.argv.slice(2), sheet = args.includes("--sheet"), maleOnly = args.includes("--male"), only = args.filter((a) => !a.startsWith("--"));
const TYPES = { ".js": "text/javascript", ".mjs": "text/javascript", ".html": "text/html" };
const server = createServer((req, res) => {
  const u = req.url.split("?")[0]; const file = u === "/" ? join(here, "page.html") : u.startsWith("/three/") ? join(root, "node_modules/three", u.slice(7)) : u.startsWith("/m/") ? join(here, u.slice(3)) : null;
  if (!file || !existsSync(file)) { res.writeHead(404).end(); return; }
  res.writeHead(200, { "content-type": TYPES[extname(file)] ?? "application/octet-stream" }).end(readFileSync(file));
});
await new Promise((r) => server.listen(0, "127.0.0.1", r));
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--use-gl=angle", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 512, height: 512 } });
page.on("pageerror", (e) => console.error("page error:", e.message)); page.on("console", (m) => m.type() === "error" && console.error("console:", m.text()));
await page.goto(`http://127.0.0.1:${server.address().port}/`); await page.waitForFunction("window.ready === true");

const list = EXERCISES.filter((e) => !only.length || only.includes(e.slug)); const tiles = [];
for (const ex of list) for (const sex of maleOnly ? ["male"] : ["male", "female"]) {
  const urls = await page.evaluate(([e, s]) => window.renderExercise(e, s), [ex, sex]);
  const dir = join(root, "public", "exercise-media", sex, ex.slug); mkdirSync(dir, { recursive: true });
  for (let i = 0; i < urls.length; i++) {
    const png = Buffer.from(urls[i].split(",")[1], "base64");
    writeFileSync(join(dir, `${i + 1}.webp`), await sharp(png).resize(480, 480).webp({ quality: 82, alphaQuality: 90 }).toBuffer());
    if (sheet) tiles.push({ input: await sharp(png).resize(256, 256).flatten({ background: "#1a1d23" }).png().toBuffer(), sex, ex: ex.slug, i });
  }
  console.log(ex.slug, sex, urls.length);
}
if (sheet && tiles.length) {
  const cols = 6, rows = Math.ceil(tiles.length / cols);
  const comp = tiles.map((t, n) => ({ input: t.input, left: (n % cols) * 256, top: Math.floor(n / cols) * 256 }));
  const out = process.env.SHEET_OUT ?? join(root, "..", "sheet.png");
  await sharp({ create: { width: cols * 256, height: rows * 256, channels: 3, background: "#1a1d23" } }).composite(comp).png().toFile(out); console.log("sheet:", out);
}
if (!only.length) { // a full run refreshes the list of exercises that have images (the app reads it, so it never links to a file that does not exist)
  writeFileSync(join(root, "src/lib/exercises/frame-slugs.ts"), `// Generated by scripts/media/build.mjs — do not edit by hand.\nexport const FRAME_SLUGS: ReadonlySet<string> = new Set(${JSON.stringify(EXERCISES.map((e) => e.slug), null, 2)});\n`);
}
await browser.close(); server.close();
